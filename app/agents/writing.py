"""How the office writes for people.

Answers read like evidence logs: analyst categories, hedging on every line,
and words no reader uses ("conditional ranking", "verification scope"). Every
role that writes for the owner follows the same few rules.
"""

WRITING_RULES = """How to write it:
- Write for the reader in the plan's reader_brief, in their language (the
  language of the request unless they asked for another) and in their words.
- Lead with the answer. Then what they need to act on it. Then the next steps.
- Plain, everyday words and short sentences. No jargon, and no words from how
  the office works: never "evidence strength", "verification", "scope",
  "conditional ranking", "candidate", "acceptance criteria", "step", "wave",
  "critic" or "the research". Say "we found" and "we could not find".
- Be concrete: names, places, prices, dates, times and links the reader can use.
- Options go in a short list or table, best first, each with why it is there.
- Say what is uncertain once, briefly, at the end, not as a hedge on every line.
  A detail the reader can simply ask for is "ask them", not a limitation.
- Do not describe the process or what was searched; describe what was found."""
